/**
 * lib/i18n.ts — Centralized i18n for GutWell AI
 *
 * Architecture:
 * - Single typed translation object (Translations) covering all core screens.
 * - Three language resources: English (en), German (de), Persian (fa).
 * - useTranslation() hook — import in any screen, reads from LanguageContext.
 * - RTL helpers for Persian layout.
 * - Keys structured by screen namespace to avoid collisions.
 * - Adding a new language: add a new key to each namespace below.
 * - Phase 2B/2C: replace hard-coded strings in each screen with t.namespace.key.
 *
 * DO NOT add Google Translate or any translation API.
 * All translations are human-authored.
 */

// ─── Types ──────────────────────────────────────────────────────────────────

export type AppLanguage = 'en' | 'de' | 'fa';

export const SUPPORTED_LANGUAGES: AppLanguage[] = ['en', 'de', 'fa'];

export const LANGUAGE_LABELS: Record<AppLanguage, string> = {
  en: 'English',
  de: 'Deutsch',
  fa: 'فارسی',
};

export const RTL_LANGUAGES: AppLanguage[] = ['fa'];

export function isRTL(lang: AppLanguage): boolean {
  return RTL_LANGUAGES.includes(lang);
}

// ─── Translation shape ───────────────────────────────────────────────────────
// We derive the shape from the English source but use a mapped type
// that widens all leaf values to string so de/fa translations compile.
type DeepString<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
  ? readonly DeepString<U>[]
  : { [K in keyof T]: DeepString<T[K]> };

export type Translations = DeepString<typeof en>;

