// ─── Translation registry ─────────────────────────────────────────────────────

export const translations: Record<AppLanguage, Translations> = { en, de, fa };

// ─── Hook ─────────────────────────────────────────────────────────────────────

import { useContext } from 'react';
import { LanguageContext } from './LanguageContext';

/**
 * useTranslation — returns the full translation object for the current language.
 * Usage:
 *   const t = useTranslation();
 *   <Text>{t.login.title}</Text>
 */
export function useTranslation(): Translations {
  const ctx = useContext(LanguageContext);
  return translations[ctx?.language ?? 'en'];
}

/**
 * getTranslation — non-hook version for use outside components.
 */
export function getTranslation(lang: AppLanguage): Translations {
  return translations[lang];
}
